import {test, expect} from '@playwright/test'
import {signIn} from './authentication.mjs'

test('unsaved edits stay safe when closing or reloading, while saved pages leave normally', async ({page}, testInfo) => {
  await signIn(page)
  await page.goto('/pages/new')
  const title=page.getByRole('textbox',{name:'Page title',exact:true})
  const editor=page.getByRole('textbox',{name:'Your page text',exact:true})
  await title.fill('A thought to keep')
  await editor.fill('A curious reader notices a wonderful discovery.')
  let message
  page.once('dialog', async dialog=>{message=dialog.message();await dialog.dismiss()})
  await page.locator('#page-close').click()
  await expect(title).toHaveValue('A thought to keep')
  await expect(editor).toHaveText('A curious reader notices a wonderful discovery.')
  expect(message).toBe('Leave without saving? Your changes will be lost.')

  const dialogPromise=page.waitForEvent('dialog')
  // page.reload waits for a navigation even when beforeunload cancels it.
  const reload=page.evaluate(()=>location.reload())
  const dialog=await dialogPromise
  expect(dialog.type()).toBe('beforeunload')
  await dialog.dismiss()
  await reload
  await expect(editor).toHaveText('A curious reader notices a wonderful discovery.')

  await page.locator('#page-save').click()
  await expect(page.locator('#page-reading')).toContainText('wonderful discovery')
  await page.waitForURL(url=>/^\/pages\/(?!new$)/.test(url.pathname))
  const url=page.url()
  await page.locator('#page-edit').click()
  await editor.fill('A changed thought, not yet saved.')
  page.once('dialog', async dialog=>{message=dialog.message();await dialog.dismiss()})
  await page.locator('#account-menu-trigger').click()
  await page.locator('#account-preferences').click()
  await expect(page).toHaveURL(url)
  await expect(editor).toHaveText('A changed thought, not yet saved.')
  await page.keyboard.press('Escape')
  await page.locator('#page-save').click()
  await expect(page.locator('#page-reading')).toContainText('A changed thought')
  await page.locator('#page-close').click()
  await expect(page.locator('#library-texts')).toContainText('A thought to keep')
  await page.reload()
  await page.getByRole('heading',{name:'A thought to keep',exact:true}).click()
  await expect(page.locator('#page-reading')).toContainText('A changed thought, not yet saved.')
  await page.screenshot({path:testInfo.outputPath('saved-page-reopened.png'),fullPage:true})
})

test('Back navigation recovers a private tab draft and successful saves clear the recovery', async ({page}) => {
  await signIn(page)
  const create=async()=>{
    await page.locator('#page-create-trigger').click()
    await page.locator('#new-free-page').click()
    await expect(page.locator('#page-title')).toBeVisible()
  }
  await create()
  const title=page.getByRole('textbox',{name:'Page title',exact:true})
  const editor=page.getByRole('textbox',{name:'Your page text',exact:true})
  await title.fill('A recoverable thought')
  await editor.fill('Keep this even if the browser goes back.')
  await page.evaluate(()=>history.back())
  await expect(page.locator('#library-texts')).toBeVisible()
  await create()
  await expect(title).toHaveValue('A recoverable thought')
  await expect(editor).toHaveText('Keep this even if the browser goes back.')
  await expect(page.locator('#page-draft-recovered')).toBeVisible()
  await page.locator('#page-save').click()
  await expect(page.locator('#page-reading p')).toHaveText('Keep this even if the browser goes back.')
  await page.locator('#page-close').click()
  await create()
  await expect(title).toHaveValue('Untitled')
  await expect(editor).toBeEmpty()
  await expect(page.locator('#page-draft-recovered')).toBeHidden()
  await title.fill('A discarded thought')
  page.once('dialog', dialog=>dialog.accept())
  await page.locator('#page-close').click()
  await expect(page.locator('#library-texts')).toBeVisible()
  await create()
  await expect(title).toHaveValue('Untitled')
  await expect(page.locator('#page-draft-recovered')).toBeHidden()
})

test('reading resumes by source block and explicit notebook references take priority', async ({page}, testInfo) => {
  await signIn(page)
  await page.goto('/pages/new')
  await page.getByRole('textbox',{name:'Page title',exact:true}).fill('A reading to return to')
  const body=Array.from({length:30},(_,index)=>`Passage ${index+1}. ${'A patient reader notices the details and keeps a thought for later. '.repeat(7)}`).join('\n\n')
  await page.getByRole('textbox',{name:'Your page text',exact:true}).evaluate((el,text)=>{
    const clipboardData=new DataTransfer();clipboardData.setData('text/plain',text)
    el.focus();el.dispatchEvent(new ClipboardEvent('paste',{bubbles:true,cancelable:true,clipboardData}))
  },body)
  await page.locator('#page-save').click()
  await expect(page.locator('#page-reading')).toBeVisible()
  await page.waitForURL(url=>/^\/pages\/(?!new$)/.test(url.pathname))
  const url=page.url()
  await page.locator('#page-block-4').evaluate(el=>{
    el.scrollIntoView()
    const node=el.querySelector('p').firstChild,range=document.createRange()
    range.setStart(node,0);range.setEnd(node,9)
    const selection=window.getSelection();selection.removeAllRanges();selection.addRange(range)
    el.dispatchEvent(new MouseEvent('mouseup',{bubbles:true}))
  })
  await page.locator('#selection-note').click()
  await page.getByLabel('Your note on the selection').fill('Return to the fifth passage.')
  await page.getByRole('button',{name:'Keep note',exact:true}).click()
  const markId=await page.locator('.mark-note.is-active').getAttribute('data-margin-mark')
  await page.locator('#page-block-18').evaluate(el=>window.scrollTo({top:el.getBoundingClientRect().top+scrollY-80,behavior:'instant'}))
  const position=await page.evaluate(()=>scrollY)
  await page.locator('#page-close').click()
  await page.getByRole('heading',{name:'A reading to return to',exact:true}).click()
  await expect.poll(()=>page.evaluate(()=>scrollY)).toBeGreaterThan(position-10)
  await expect.poll(()=>page.locator('#page-block-18').evaluate(el=>Math.abs(el.getBoundingClientRect().top-80))).toBeLessThan(10)
  await page.reload()
  await expect.poll(()=>page.locator('#page-block-18').evaluate(el=>Math.abs(el.getBoundingClientRect().top-80))).toBeLessThan(10)
  await page.screenshot({path:testInfo.outputPath('resumed-reading.png'),fullPage:false})
  await page.locator('#page-close').click()
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('heading',{name:'A reading to return to',exact:true}).click()
  await expect.poll(()=>page.locator('#page-block-18').evaluate(el=>Math.abs(el.getBoundingClientRect().top-80))).toBeLessThan(10)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.goto('/notebook')
  await page.locator(`#notebook-source-${markId}`).click()
  await expect(page).toHaveURL(`${url}?mark=${markId}`)
  await expect(page.locator('#page-block-4')).toHaveClass(/is-flash/)
  await expect.poll(()=>page.locator('#page-block-4').evaluate(el=>{const rect=el.getBoundingClientRect();return rect.top>=60&&rect.top<innerHeight})).toBe(true)
  await page.screenshot({path:testInfo.outputPath('source-reference-mobile.png'),fullPage:false})
  await page.locator('#page-edit').click()
  await page.getByRole('textbox',{name:'Your page text',exact:true}).fill('A shorter revised page.')
  await page.locator('#page-save').click()
  await expect(page.locator('#page-reading p')).toHaveText('A shorter revised page.')
  await expect.poll(()=>page.evaluate(()=>scrollY)).toBe(0)
})
