async function textSize(page, size) {
  await page.locator('#reading-text-size').evaluate((input,value)=>{
    input.value=String(value)
    input.dispatchEvent(new Event('input',{bubbles:true}))
  },size)
  await expect(page.locator('#reading-size-value')).toHaveText(String(size))
}

async function wordPoint(page, block, quote) {
  return page.locator(`#page-block-${block}`).evaluate((el,quote)=>{
    const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);let node
    while((node=walker.nextNode())){
      const at=node.textContent.indexOf(quote)
      if(at>=0){const r=document.createRange();r.setStart(node,at);r.setEnd(node,at+quote.length);const box=r.getBoundingClientRect();return {x:box.x+box.width/2,y:box.y+box.height/2}}
    }
    throw new Error(`Missing word: ${quote}`)
  },quote)
}

