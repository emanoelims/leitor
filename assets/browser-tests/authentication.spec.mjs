import {test,expect} from '@playwright/test'
import {signIn} from './authentication.mjs'

test('email links are the only way to sign in and inputs match Gloss',async({page})=>{
  await page.emulateMedia({colorScheme:"light",reducedMotion:"reduce"})
  await signIn(page)
  await page.goto('/users/settings')
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  await expect(page.locator('#password_form')).toHaveCount(0)
  const email=await page.locator('#email_form input[type=email]').inputValue()
  await page.locator('#account-menu-trigger').click()
  await page.locator('#header-log-out').click()
  await page.waitForURL('**/users/log-in')
  await page.locator('[data-phx-main].phx-connected').waitFor()
  await expect(page.locator('#login_form_magic input[type=email]')).toHaveCount(1)
  await expect(page.locator('input[type=password],#login_form_password')).toHaveCount(0)
  const input=page.getByRole('textbox',{name:'Email',exact:true})
  await expect(input).toHaveCSS('height','36px')
  await expect(input).toHaveCSS('border-radius','8px')
  await expect(input).toHaveCSS('padding-left','12px')
  await expect(input).toHaveCSS('font-size','13px')
  await input.focus()
  await expect(input).toHaveCSS('outline-style','none')
  await expect(input).toHaveCSS('border-color','rgb(211, 202, 184)')
  await expect(page.locator('#brand-home')).toHaveAccessibleName('Leitor home')
  await expect(page.locator('#brand-home .brand-symbol')).toBeVisible()
  await expect(page.locator('link[rel=icon]')).toHaveAttribute('href','/images/logo.svg')
  const icon=await page.request.get('/images/logo.svg')
  expect(icon.ok()).toBe(true)
  expect(await icon.text()).toContain('<circle class="note"')
  await page.locator('#flash-error button').click()
  await expect(page.locator('#flash-error')).toBeHidden()
  await page.locator('#flash-info button').click()
  await expect(page.locator('#flash-info')).toBeHidden()
  await page.screenshot({path:'../tmp/leitor-entry-desktop.png',fullPage:false})
  await page.setViewportSize({width:390,height:844})
  await expect(input).toBeInViewport()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await expect(page.locator('#magic-link-submit')).toBeInViewport()
  const headerAlignment=await page.locator('.auth-header').evaluate(el=>{
    const brand=el.querySelector('#brand-home').getBoundingClientRect()
    const action=el.querySelector('.auth-header-link').getBoundingClientRect()
    return Math.abs((brand.top+brand.height/2)-(action.top+action.height/2))
  })
  expect(headerAlignment).toBeLessThan(3)
  await page.screenshot({path:'../tmp/leitor-entry-mobile.png',fullPage:false})
  await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'})
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
  await expect(page.locator('#brand-home')).toHaveCSS('color','rgb(233, 227, 214)')
  await page.screenshot({path:'../tmp/leitor-entry-dark-mobile.png',fullPage:false})
  await page.emulateMedia({colorScheme:'light',reducedMotion:'reduce'})
  await input.fill('not-an-email')
  await page.locator('#magic-link-submit').click()
  expect(await input.evaluate(el=>el.validity.typeMismatch)).toBe(true)
  await input.fill(email)
  await page.locator('#magic-link-submit').click()
  await expect(page.getByText('If your email is valid, a sign-in link will arrive shortly. Check your inbox.')).toBeVisible()
  const response=await page.request.get('/dev/mailbox/json')
  const message=(await response.json()).data.find(item=>item.to.some(recipient=>recipient.includes(email)))
  const link=message.text_body.match(/http[^\s]+\/users\/log-in\/[^\s]+/)[0]
  await page.goto(link)
  await page.locator('[data-phx-main].phx-connected').waitFor()
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  await page.locator('#login-once-submit').click()
  await expect(page.locator('#library-texts')).toBeVisible()
  await page.goto(link)
  await expect(page).toHaveURL(/\/users\/log-in$/)
  await expect(page.getByText('Magic link is invalid or it has expired.')).toBeVisible()
})
