import {test, expect} from '@playwright/test'
import {signIn} from './authentication.mjs'

test('workspace and account share compact popup items and keyboard navigation', async ({page}, testInfo) => {
  const errors=[]
  page.on('pageerror', error=>errors.push(error.message))
  await signIn(page)
  const account=page.locator('#account-menu-trigger')
  const context=page.locator('#workspace-context-trigger')
  await account.focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('#account-menu-panel')).toBeVisible()
  await expect(page.locator('#account-menu-panel')).toHaveAttribute('role','menu')
  await expect(page.locator('#account-menu-panel')).toHaveCSS('padding','6px')
  await expect(page.locator('#account-preferences')).toBeFocused()
  for (const id of ['account-preferences','account-settings','header-log-out']) {
    const item=page.locator('#'+id)
    await expect(item).toHaveCSS('text-decoration-line','none')
    await expect(item).toHaveCSS('font-weight','400')
    await expect(item).toHaveCSS('min-height','36px')
    expect(await item.locator('span').first().evaluate(el=>getComputedStyle(el).maskImage)).not.toBe('none')
  }
  await page.keyboard.press('ArrowDown')
  await expect(page.locator('#account-settings')).toBeFocused()
  await page.keyboard.press('End')
  await expect(page.locator('#header-log-out')).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.locator('#account-preferences')).toBeFocused()
  await page.keyboard.press('Home')
  await expect(page.locator('#account-preferences')).toBeFocused()
  await page.screenshot({path:testInfo.outputPath('account-menu-light.png')})
  await page.keyboard.press('Escape')
  await expect(account).toBeFocused()
  await expect(page.locator('#account-menu-panel')).toBeHidden()
  await context.focus()
  await page.keyboard.press('ArrowUp')
  await expect(page.locator('#page-new')).toBeFocused()
  await expect(page.locator('#workspace-pages')).toHaveAttribute('aria-current','page')
  await expect(page.locator('#workspace-context-panel')).toHaveCSS('opacity','1')
  await page.screenshot({path:testInfo.outputPath('workspace-menu-light.png')})
  await account.click()
  await expect(page.locator('#workspace-context-panel')).toBeHidden()
  await page.locator('#main-content').click({position:{x:20,y:20}})
  await expect(page.locator('#account-menu-panel')).toBeHidden()
  await account.click()
  await expect(page.locator('#account-preferences')).toBeFocused()
  await page.keyboard.press('Space')
  await expect(page).toHaveURL(/\/settings$/)
  await account.click()
  await expect(page.locator('#account-preferences')).toHaveAttribute('aria-current','page')
  await page.keyboard.press('Tab')
  await expect(page.locator('#account-menu-panel')).toBeHidden()
  await page.evaluate(()=>localStorage.setItem('leitor:theme','ink'))
  await page.reload()
  await page.setViewportSize({width:390,height:844})
  await account.click()
  await expect(page.locator('#account-menu-panel')).toBeInViewport()
  await expect(page.locator('#header-log-out')).toBeInViewport()
  await expect(page.locator('#account-menu-panel')).toHaveCSS('opacity','1')
  await page.screenshot({path:testInfo.outputPath('account-menu-ink-mobile.png')})
  await page.locator('#header-log-out').click()
  await expect(page).toHaveURL(/\/users\/log-in$/)
  expect(errors).toEqual([])
})

test('select popups preserve values and nested filters stay open', async ({page}, testInfo) => {
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await signIn(page)
  await page.goto('/settings')
  const model=page.locator('#preferences-reading-model-trigger')
  await model.focus()
  await page.keyboard.press('Enter')
  const options=page.locator('#preferences-reading-model-options')
  await expect(options).toBeVisible()
  await expect(options.locator('[aria-selected=true]')).toBeFocused()
  await expect(options).toHaveCSS('opacity','1')
  await expect(options.getByRole('option').first()).toHaveCSS('text-align','left')
  expect(await options.evaluate(el=>Math.round(el.getBoundingClientRect().width))).toBe(await model.evaluate(el=>Math.round(el.getBoundingClientRect().width)))
  await page.screenshot({path:testInfo.outputPath('claude-select-popup.png')})
  await page.keyboard.press('End')
  await page.keyboard.press('Enter')
  await expect(model).toBeFocused()
  await expect(model).toContainText('Claude Haiku 5.5')
  await expect(page.locator('#preferences-reading-model')).toHaveValue('anthropic:claude-haiku-5-5')
  await page.locator('#save-preferences').click()
  await expect(page.getByText('Preferences saved.',{exact:true})).toBeVisible()
  await expect(model).toContainText('Claude Haiku 5.5')
  const language=page.locator('#preferences-ai-locale-trigger')
  await page.locator('#preferences-ai-locale-label').click()
  await expect(page.locator('#preferences-ai-locale-options [aria-selected=true]')).toBeFocused()
  await page.keyboard.press('p')
  await expect(page.getByRole('option',{name:'Português (Brasil)',exact:true})).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(language).toContainText('Follow the request')
  await expect(language).toBeFocused()
  await page.locator('#preferences-ai-locale').evaluate(el=>{el.disabled=true})
  await expect(language).toHaveAttribute('aria-disabled','true')
  await language.click({force:true})
  await expect(page.locator('#preferences-ai-locale-options')).toBeHidden()
  await page.goto('/pages')
  await page.locator('#workspace-filters-trigger').click()
  await page.locator('#library-order-trigger').click()
  await expect(page.locator('#workspace-filters-panel')).toBeVisible()
  await expect(page.locator('#library-order-options')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('#library-order-options')).toBeHidden()
  await expect(page.locator('#workspace-filters-panel')).toBeVisible()
  await page.locator('#library-order-trigger').click()
  await page.getByRole('option',{name:'Title A–Z',exact:true}).click()
  await expect(page).toHaveURL(/sort=title/)
  await expect(page.locator('#library-order-trigger')).toContainText('Title A–Z')
  await expect(page.locator('#library-order')).toHaveCSS('width','1px')
  await expect(page.locator('#library-order')).toHaveAttribute('aria-hidden','true')
  await expect(page.locator('#workspace-filters-panel')).toBeVisible()
  await page.locator('#library-order-trigger').click()
  await expect(page.locator('#library-order-options')).toHaveCSS('opacity','1')
  await page.screenshot({path:testInfo.outputPath('nested-select-popup.png')})
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await expect(page.locator('#workspace-filters-panel')).toBeHidden()
  await page.goto('/settings')
  await page.setViewportSize({width:390,height:844})
  await page.locator('#preferences-locale-trigger').click()
  await expect(page.locator('#preferences-locale-options')).toBeInViewport()
  await expect(page.locator('#preferences-locale-options')).toHaveCSS('opacity','1')
  await page.screenshot({path:testInfo.outputPath('language-select-mobile.png')})
  await page.goto('/pages/new')
  await page.locator('#page-title').fill('Menu keyboard scope')
  await page.getByRole('textbox',{name:'Your page text'}).fill('A quiet page.')
  await page.locator('#page-save').click()
  await expect(page.locator('#page-reading')).toBeVisible()
  await page.locator('#account-menu-trigger').click()
  await expect(page.locator('#account-preferences')).toBeFocused()
  await page.keyboard.press('n')
  await expect(page.locator('#page-notebook-panel')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(page.locator('#account-menu-trigger')).toBeFocused()
  expect(errors).toEqual([])
})
