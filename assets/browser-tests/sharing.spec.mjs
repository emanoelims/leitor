import {test,expect} from '@playwright/test'
import {writeFile} from 'node:fs/promises'
import {signIn} from './authentication.mjs'
import {chooseOption} from './controls.mjs'

async function select(page,quote) {
  await page.locator("[data-phx-main].phx-connected").waitFor()
  await page.locator('#page-block-0').evaluate((node,quote)=>{
    const walker=document.createTreeWalker(node,NodeFilter.SHOW_TEXT)
    let text;while((text=walker.nextNode())&&!text.textContent.includes(quote)){}
    if(!text) throw new Error('Selection quote is missing')
    const from=text.textContent.indexOf(quote),range=document.createRange()
    range.setStart(text,from);range.setEnd(text,from+quote.length)
    const selected=window.getSelection();selected.removeAllRanges();selected.addRange(range)
    node.dispatchEvent(new MouseEvent('mouseup',{bubbles:true}))
  },quote)
  await expect(page.locator('#page-selection')).toBeVisible()
}

test('sharing permissions, guest conversations and private notes work across independent browsers',async({page,browser},testInfo)=>{
  test.setTimeout(90000)
  await signIn(page)
  await page.goto('/pages/new')
  await page.getByRole('textbox',{name:'Page title'}).fill('A page to share')
  await page.getByRole('textbox',{name:'Your page text'}).evaluate(node=>{
    node.focus();const data=new DataTransfer()
    data.setData('text/plain','A wonderful discovery starts with a little attention.\n\n```leitor-svg-sway\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 100"><title>A moving circle</title><circle cx="100" cy="50" r="20" fill="#b67c4c"/></svg>\n```')
    node.dispatchEvent(new ClipboardEvent('paste',{bubbles:true,cancelable:true,clipboardData:data}))
  })
  await page.locator('#page-save').click()
  await page.locator('#page-share').click()
  await expect(page.locator('#page-sharing-dialog')).toBeVisible()
  const link=await page.locator('#open-shared-page').getAttribute('href')
  const sharedUrl=new URL(link,page.url()).href
  const guestContext=await browser.newContext({baseURL:new URL(page.url()).origin,viewport:{width:1440,height:960}})
  const observerContext=await browser.newContext({baseURL:new URL(page.url()).origin,viewport:{width:1440,height:960}})
  try {
    const guest=await guestContext.newPage(),observer=await observerContext.newPage()
    const errors=[];guest.on("pageerror",error=>errors.push(error.message));observer.on("pageerror",error=>errors.push(error.message))
    await guest.goto(sharedUrl)
    await expect(guest.locator('#shared-page-unavailable')).toBeVisible()
    await chooseOption(page,page.getByRole('combobox',{name:'General access',exact:true}),'comment')
    await guest.reload()
    await expect(guest.locator('#page-reading')).toContainText('wonderful')
    await expect(guest.locator('#page-edit')).toHaveCount(0)
    await expect(guest.locator('.page-illustration img')).toHaveAttribute('alt','A moving circle')
    const pause=guest.locator('[data-illustration-toggle]')
    await pause.click()
    await expect(pause).toHaveAttribute('aria-pressed','true')
    await observer.goto(sharedUrl)
    await observer.locator("[data-phx-main].phx-connected").waitFor()
    await select(guest,'wonderful')
    await guest.locator('#selection-comment').click()
    await guest.getByLabel('Display name',{exact:true}).fill('Ana')
    await guest.getByLabel('Comment',{exact:true}).fill('Could we explain this passage together?')
    await guest.getByRole('button',{name:'Post comment',exact:true}).click()
    await expect(guest.locator('#shared-comment-form')).toHaveCount(0)
    await expect(guest.locator('#shared-action-error')).toHaveCount(0)
    await expect(guest.locator('#shared-comments')).toContainText('Could we explain this passage together?')
    await expect(observer.locator('#shared-comments')).toContainText('Could we explain this passage together?')
    await observer.locator('#shared-comments').getByRole('button',{name:'Reply',exact:true}).click()
    await observer.getByLabel('Display name',{exact:true}).fill('Bruno')
    await observer.getByLabel('Comment',{exact:true}).fill('Yes, this refers to the discovery.')
    await observer.getByRole('button',{name:'Post comment',exact:true}).click()
    await expect(guest.locator('#shared-comments')).toContainText('Yes, this refers to the discovery.')
    await select(guest,'wonderful')
    await guest.locator('#selection-note').click()
    await guest.getByLabel('Your note on the selection').fill('My private guest thought')
    await guest.getByRole('button',{name:'Keep note',exact:true}).click()
    await expect(guest.locator('#shared-personal-notes')).toContainText('My private guest thought')
    await observer.locator('#personal-tab').click()
    await expect(observer.locator('#shared-personal-notes')).not.toContainText('My private guest thought')
    await guest.reload()
    await guest.locator('#personal-tab').click()
    await expect(guest.locator('#shared-personal-notes')).toContainText('My private guest thought')
    await select(guest,'wonderful')
    await guest.locator('#selection-explain').click()
    await expect(guest.locator('#shared-action-error')).toContainText('Sign in')
    await guest.keyboard.press('Escape')
    await guest.locator('#shared-tab').click()
    await guest.setViewportSize({width:390,height:844})
    await expect(guest.locator('#shared-comments')).toContainText('Could we explain this passage together?')
    await guest.screenshot({path:testInfo.outputPath('shared-page-mobile.png'),fullPage:true})
    await guest.setViewportSize({width:1440,height:960})
    await guest.screenshot({path:testInfo.outputPath('shared-page-desktop.png'),fullPage:false})
    await page.screenshot({path:testInfo.outputPath('share-permissions.png')})
    await signIn(guest)
    await guest.goto(sharedUrl)
    await guest.locator('#personal-tab').click()
    await guest.locator('#import-guest-notes').click()
    await expect(guest.locator('#import-guest-notes')).toHaveCount(0)
    await expect(guest.locator('#shared-personal-notes')).toContainText('My private guest thought')
    await guest.reload()
    await guest.locator('#personal-tab').click()
    await expect(guest.locator('#shared-personal-notes')).toContainText('My private guest thought')
    await guest.locator('#shared-tab').click()
    await page.locator('#renew-share-link').click()
    await expect(guest.locator('#shared-page-unavailable')).toBeVisible()
    await expect(observer.locator('#shared-page-unavailable')).toBeVisible()
    const renewed=await page.locator('#open-shared-page').getAttribute('href')
    expect(renewed).not.toBe(link)
    await guest.goto(new URL(renewed,page.url()).href)
    await expect(guest.locator('#page-reading')).toBeVisible()
    await chooseOption(page,page.getByRole('combobox',{name:'General access',exact:true}),'view')
    await expect(guest.getByText('The owner has enabled viewing only.')).toBeVisible()
    await select(guest,'wonderful')
    await expect(guest.locator('#selection-comment')).toHaveCount(0)
    await chooseOption(page,page.getByRole('combobox',{name:'General access',exact:true}),'disabled')
    await expect(guest.locator('#shared-page-unavailable')).toBeVisible()
    expect(errors).toEqual([])
    await writeFile(testInfo.outputPath('sharing-result.json'),JSON.stringify({pageUrl:page.url(),sharedUrl,passed:true}))
  } finally {
    await Promise.allSettled([guestContext.close(),observerContext.close()])
  }
})
