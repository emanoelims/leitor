import {writeFile} from "node:fs/promises"
import {test, expect} from "@playwright/test"
import {signIn, paste} from "./writing_helpers.mjs"

const editorFor = page => page.getByRole("textbox", {name: "Your English text", exact: true})
async function block(page, command, text) {
  const editor = editorFor(page)
  await editor.pressSequentially("/")
  await page.locator(`#writing-block-${command}`).click()
  if (text) await editor.pressSequentially(text)
}

// A complete writing session, using actual keystrokes and commands rather than
// setting the editor's internal document or accepting its Markdown as ground truth.
test("compose a complete article with every block and inline style", async ({page}) => {
  test.setTimeout(120000)
  const errors = []
  page.on("pageerror", error => errors.push(error.message))
  await signIn(page)
  const editor = editorFor(page)
  await block(page, "h1", "A Saturday in Belém")
  await editor.press("Enter")
  await editor.pressSequentially("A **small** discovery felt *important*, ~~perfect~~ honest, and `memorable`. ")
  await editor.pressSequentially("Read [my notes](https://example.com/notes) for more.")
  await expect(editor.locator("strong")).toHaveText("small")
  await expect(editor.locator("em")).toHaveText("important")
  await expect(editor.locator("s")).toHaveText("perfect")
  await expect(editor.locator("p code")).toHaveText("memorable")
  await expect(editor.locator("a")).toHaveText("my notes")
  await editor.press("Enter")
  await block(page, "h2", "The market")
  await editor.press("Enter")
  await block(page, "h3", "Things I noticed")
  await editor.press("Enter")
  await block(page, "bullet", "Fresh fruit")
  await editor.press("Enter")
  await editor.pressSequentially("Local stories")
  await editor.press("Tab")
  await expect(editor.locator("ul ul li")).toHaveText("Local stories")
  await editor.press("Enter")
  await editor.press("Enter")
  await editor.press("Enter")
  await block(page, "ordered", "Listen carefully")
  await editor.press("Enter")
  await editor.pressSequentially("Write a few notes")
  await editor.press("Enter")
  await editor.press("Enter")
  await block(page, "task", "Buy a notebook")
  await editor.press("Enter")
  await editor.pressSequentially("Call a friend")
  await editor.press("Enter")
  await editor.press("Enter")
  await editor.getByRole("checkbox", {name:"Task item checkbox for Buy a notebook"}).check()
  await editor.press(process.platform === "darwin" ? "Meta+ArrowDown" : "Control+End")
  await block(page, "quote", "Pay attention to small things.")
  await editor.press("Shift+Enter")
  await editor.pressSequentially("They often matter most.")
  await editor.press("Enter")
  await editor.press("Enter")
  await block(page, "code", 'IO.puts("Olá, mundo")')
  await editor.press("Enter")
  await editor.pressSequentially("# A code comment")
  await editor.press("Enter")
  await editor.press("Enter")
  await editor.press("Enter")
  await block(page, "divider")
  await editor.pressSequentially("I came home with more than a notebook.")
  await expect(editor.locator("h1")).toHaveText("A Saturday in Belém")
  await expect(editor.locator("h2")).toHaveText("The market")
  await expect(editor.locator("h3")).toHaveText("Things I noticed")
  await expect(editor.locator("ol li")).toHaveText(["Listen carefully", "Write a few notes"])
  await expect(editor.locator("blockquote")).toContainText("They often matter most.")
  await expect(editor.locator("pre")).toContainText('# A code comment')
  await expect(editor.locator("hr")).toHaveCount(1)
  const source = await page.locator("#writing_text").inputValue()
  await writeFile("../tmp/writing-example.md", source)
  await page.locator("#writing-preview-toggle").click()
  await expect(page.locator("#writing-preview h1")).toHaveText("A Saturday in Belém")
  await expect(page.locator("#writing-preview a")).toHaveText("my notes")
  await expect(page.locator("#writing-preview ul ul li")).toHaveText("Local stories")
  await expect(page.locator("#writing-preview input[checked]")).toHaveCount(1)
  await page.screenshot({path:"../tmp/writing-full-preview.png", fullPage:true})
  await page.locator("#save-draft").click()
  await expect(page.locator("#writing-save-status")).toContainText("Draft saved")
  await page.reload()
  await page.locator("[data-phx-main].phx-connected").waitFor()
  await page.locator("#writing-history-toggle").click()
  await page.locator(".writing-history-open").first().click()
  await expect(page.locator("#writing_text")).toHaveValue(source)
  await expect(editor.locator("ul ul li")).toHaveText("Local stories")
  await expect(editor.locator("a")).toHaveText("my notes")
  await expect(editor.locator("blockquote br")).toHaveCount(1)
  await expect(editor.locator("pre")).toContainText('# A code comment')
  await expect(editor.getByRole("checkbox").first()).toBeChecked()
  await page.getByRole("button", {name:"Toggle dark theme"}).click()
  await expect(page.locator("#review-paragraph")).toHaveCSS("background-color", "rgb(239, 238, 230)")
  await expect(page.locator("#review-paragraph")).toHaveCSS("color", "rgb(27, 29, 26)")
  await page.screenshot({path:"../tmp/writing-full-dark.png", fullPage:true})
  await page.getByRole("button", {name:"Toggle dark theme"}).click()
  await expect(page.locator("#review-paragraph")).toHaveCSS("background-color", "rgb(20, 20, 19)")
  await page.setViewportSize({width:320,height:740})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({path:"../tmp/writing-full-mobile.png", fullPage:true})
  await page.setViewportSize({width:1440,height:960})
  await page.screenshot({path:"../tmp/writing-full-editor.png", fullPage:true})
  expect(errors).toEqual([])
})

test("blank paragraphs and undo history survive saving and reopening predictably", async ({page}) => {
  await signIn(page)
  const editor = editorFor(page)
  await editor.pressSequentially("First paragraph.")
  await editor.press("Enter")
  await editor.press("Enter")
  await editor.pressSequentially("Third paragraph.")
  await expect(editor.locator("p")).toHaveCount(3)
  await page.locator("#writing-preview-toggle").click()
  await expect(page.locator("#writing-preview p")).toHaveCount(3)
  await page.locator("#writing-preview-toggle").click()
  await page.locator("#save-draft").click()
  await expect(page.locator("#writing-save-status")).toContainText("Draft saved")
  await editor.press("ControlOrMeta+a")
  await editor.pressSequentially("A different draft.")
  await page.locator("#writing-history-toggle").click()
  await page.locator(".writing-history-open").first().click()
  await expect(editor.locator("p")).toHaveCount(3)
  await editor.press("ControlOrMeta+z")
  await expect(editor).not.toContainText("A different draft.")
})

test("checklists align inline in the editor and preview, and typing stays above the toolbar", async ({page}) => {
  await signIn(page)
  const editor = editorFor(page)
  await paste(page, "- [ ] First task\n- [x] Second task\n\n" + "A paragraph to fill the page.\n\n".repeat(18))
  const task = editor.locator('ul[data-type="taskList"] > li').first()
  const positions = await task.evaluate(el => ({box:el.querySelector('input').getBoundingClientRect().toJSON(),text:el.querySelector('p').getBoundingClientRect().toJSON()}))
  expect(positions.box.right).toBeLessThan(positions.text.left)
  expect(positions.box.top).toBeGreaterThanOrEqual(positions.text.top)
  expect(positions.box.bottom).toBeLessThanOrEqual(positions.text.bottom)
  await editor.press(process.platform === "darwin" ? "Meta+ArrowDown" : "Control+End")
  await editor.pressSequentially("The final line should remain visible.")
  const caret = await editor.evaluate(() => window.getSelection().getRangeAt(0).getBoundingClientRect().toJSON())
  const toolbar = await page.locator("#writing-toolbar").boundingBox()
  expect(caret.bottom).toBeLessThan(toolbar.y)
  await page.locator("#writing-preview-toggle").click()
  const previewTask = page.locator('#writing-preview li').first()
  expect(await previewTask.evaluate(el => getComputedStyle(el).listStyleType)).toBe("none")
})

test("slash commands can return from a list to text and dismiss when focus leaves", async ({page}) => {
  await signIn(page)
  const editor = editorFor(page)
  await block(page, "bullet", "A list item")
  await editor.press("Enter")
  await block(page, "paragraph", "A normal paragraph")
  await expect(editor.locator(":scope > p").filter({hasText:"A normal paragraph"})).toBeVisible()
  await editor.press("Enter")
  await editor.pressSequentially("/")
  await expect(page.locator("#writing-block-menu")).toBeVisible()
  await editor.press("Tab")
  await expect(page.locator("#writing-block-menu")).toBeHidden()
})

test("nested tasks, blank lines, and code select the correct review paragraph", async ({page}) => {
  await signIn(page)
  const editor = editorFor(page)
  await paste(page, "# Heading\n\nParagraph **one**.\n\n- Parent\n  - Child\n\n- [ ] Task\n  - [x] Nested task\n\n> Quoted\n\n```\ncode\n```\n\nAfter code.")
  const blocks = editor.locator("h1, p").filter({hasText:/\S/})
  const count = await blocks.count()
  for (let index = 0; index < count; index++) {
    await blocks.nth(index).click()
    await expect(page.locator("#writing-paragraph")).toHaveValue(String(index))
    await expect(page.locator("#app-header")).toContainText(`Paragraph ${index + 1} of ${count}`)
  }
  await editor.locator("pre").click()
  await expect(page.locator("#writing-paragraph")).toHaveValue("-1")
  await expect(page.locator("#app-header")).toContainText("Select a paragraph")
  await editor.press(process.platform === "darwin" ? "Meta+ArrowDown" : "Control+End")
  await expect(page.locator("#writing-paragraph")).toHaveValue(String(count - 1))
  await editor.press("Enter")
  await editor.press("Enter")
  await editor.pressSequentially("One last paragraph.")
  await expect(page.locator("#app-header")).toContainText(`Paragraph ${count + 1} of ${count + 1}`)
})

test("links can be typed, undone, and pasted without activating unsafe URLs", async ({page}) => {
  await signIn(page)
  const editor = editorFor(page)
  await editor.pressSequentially("[Link](https://example.com)")
  await expect(editor.locator("a")).toHaveText("Link")
  await editor.press("Backspace")
  await expect(editor.locator("a")).toHaveCount(0)
  await expect(editor).toContainText("[Link](https://example.com)")
  await editor.press("ControlOrMeta+a")
  await editor.pressSequentially("[unsafe](javascript:alert)")
  await expect(editor.locator("a[href^='javascript:']")).toHaveCount(0)
  await editor.press("Enter")
  await paste(page, "[another](javascript:alert(1))")
  await expect(editor.locator("a[href^='javascript:']")).toHaveCount(0)
})
