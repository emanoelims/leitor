defmodule Leitor.Study do
  @moduledoc """
  Owns study rooms and authorizes invitation-based collaboration.

  CRUD operations are scoped to the host. An authenticated account holding a
  private invitation can read a shared room; only the host can change its text.
  """

  import Ecto.Query, warn: false

  alias Leitor.Accounts.Scope
  alias Leitor.Library.Reading
  alias Leitor.Repo
  alias Leitor.Study.Room

  @doc """
  Subscribes to scoped notifications about any room changes.

  The broadcasted messages match the pattern:

    * `{:created, %Room{}}`
    * `{:updated, %Room{}}`
    * `{:deleted, %Room{}}`

  """
  @spec subscribe_rooms(Scope.t()) :: :ok
  def subscribe_rooms(%Scope{} = scope) do
    key = scope.user.id

    Phoenix.PubSub.subscribe(Leitor.PubSub, "user:#{key}:rooms")
  end

  defp broadcast_room(%Scope{} = scope, message) do
    key = scope.user.id

    Phoenix.PubSub.broadcast(Leitor.PubSub, "user:#{key}:rooms", message)
  end

  @doc """
  Returns the list of rooms.

  """
  @spec list_rooms(Scope.t()) :: [Room.t()]
  def list_rooms(%Scope{} = scope) do
    Repo.all_by(Room, user_id: scope.user.id)
  end

  @doc """
  Gets a single room.

  Raises `Ecto.NoResultsError` if the Room does not exist.

  """
  @spec get_room!(Scope.t(), Ecto.UUID.t()) :: Room.t()
  def get_room!(%Scope{} = scope, id) do
    Repo.get_by!(Room, id: id, user_id: scope.user.id)
  end

  @doc """
  Creates a room.

  """
  @spec create_room(Scope.t(), map()) :: {:ok, Room.t()} | {:error, Ecto.Changeset.t()}
  def create_room(%Scope{} = scope, attrs) do
    with {:ok, %Room{} = room} <-
           %Room{}
           |> Room.changeset(attrs, scope)
           |> Repo.insert() do
      broadcast_room(scope, {:created, room})
      {:ok, room}
    end
  end

  @doc """
  Updates a room.

  """
  @spec update_room(Scope.t(), Room.t(), map()) :: {:ok, Room.t()} | {:error, Ecto.Changeset.t()}
  def update_room(%Scope{} = scope, %Room{} = room, attrs) do
    true = room.user_id == scope.user.id

    with {:ok, %Room{} = room} <-
           room
           |> Room.changeset(attrs, scope)
           |> Repo.update() do
      broadcast_room(scope, {:updated, room})
      Phoenix.PubSub.broadcast(Leitor.PubSub, topic(room), {:room_updated, room})
      {:ok, room}
    end
  end

  @doc """
  Deletes a room.

  """
  @spec delete_room(Scope.t(), Room.t()) :: {:ok, Room.t()} | {:error, Ecto.Changeset.t()}
  def delete_room(%Scope{} = scope, %Room{} = room) do
    true = room.user_id == scope.user.id

    with {:ok, %Room{} = room} <-
           Repo.delete(room) do
      broadcast_room(scope, {:deleted, room})
      Phoenix.PubSub.broadcast(Leitor.PubSub, topic(room), :room_closed)
      {:ok, room}
    end
  end

  @doc """
  Returns an `%Ecto.Changeset{}` for tracking room changes.

  """
  @spec change_room(Scope.t(), Room.t(), map()) :: Ecto.Changeset.t()
  def change_room(%Scope{} = scope, %Room{} = room, attrs \\ %{}) do
    true = room.user_id == scope.user.id

    Room.changeset(room, attrs, scope)
  end

  @doc "Creates a shared room with an unguessable invitation generated by the server."
  @spec open_room(Scope.t(), map()) :: {:ok, Room.t()} | {:error, Ecto.Changeset.t()}
  def open_room(%Scope{} = scope, attrs) do
    attrs = Map.take(attrs, ["title", "body"])

    create_room(
      scope,
      Map.merge(attrs, %{
        "position" => 0,
        "invite_code" => Base.url_encode64(:crypto.strong_rand_bytes(24), padding: false)
      })
    )
  end

  @doc "Resolves an invitation for an authenticated participant, or returns not found."
  @spec join_room(Scope.t(), String.t()) :: {:ok, Room.t()} | {:error, :not_found}
  def join_room(%Scope{user: %{id: _}}, code) when is_binary(code) do
    case Repo.get_by(Room, invite_code: code) do
      nil -> {:error, :not_found}
      room -> {:ok, room}
    end
  end

  @doc "Subscribes an invited participant to live room updates."
  @spec subscribe_room(Scope.t(), String.t()) :: {:ok, Room.t()} | {:error, :not_found}
  def subscribe_room(scope, code) do
    with {:ok, room} <- join_room(scope, code) do
      :ok = Phoenix.PubSub.subscribe(Leitor.PubSub, topic(room))
      {:ok, room}
    end
  end

  @doc "Returns the private PubSub topic for an authorized room."
  @spec topic(Room.t()) :: String.t()
  def topic(%Room{id: id}), do: "study:room:#{id}"

  @doc "Moves the shared reading position. Only the host can advance the room."
  @spec advance_room(Scope.t(), String.t(), :next | :previous) ::
          {:ok, Room.t()} | {:error, :not_found | :forbidden | Ecto.Changeset.t()}
  def advance_room(%Scope{} = scope, code, direction) when direction in [:next, :previous] do
    with {:ok, room} <-
           Repo.transact(fn ->
             room = Repo.one(from room in Room, where: room.invite_code == ^code, lock: "FOR UPDATE")
             advance_locked(scope, room, direction)
           end) do
      broadcast_room(scope, {:updated, room})
      Phoenix.PubSub.broadcast(Leitor.PubSub, topic(room), {:room_updated, room})
      {:ok, room}
    end
  end

  defp advance_locked(_scope, nil, _direction), do: {:error, :not_found}
  defp advance_locked(scope, %Room{user_id: owner}, _direction) when owner != scope.user.id, do: {:error, :forbidden}

  defp advance_locked(scope, room, direction) do
    last = max(length(Reading.prepare(room.body)) - 1, 0)
    step = if direction == :next, do: 1, else: -1
    room |> Room.changeset(%{position: (room.position + step) |> max(0) |> min(last)}, scope) |> Repo.update()
  end

  @doc "Sends a bounded, ephemeral message to an active invitation's participants."
  @spec send_message(Scope.t(), String.t(), String.t()) :: :ok | {:error, :not_found | :invalid_message}
  def send_message(%Scope{} = scope, code, text) when is_binary(text) do
    text = String.trim(text)

    with true <- String.length(text) in 1..500,
         {:ok, room} <- join_room(scope, code) do
      message = %{id: Ecto.UUID.generate(version: 7), name: participant_name(scope), body: text}
      Phoenix.PubSub.broadcast(Leitor.PubSub, topic(room), {:room_message, message})
    else
      false -> {:error, :invalid_message}
      {:error, :not_found} -> {:error, :not_found}
    end
  end

  @doc "Returns a stable pseudonym without exposing the participant's email."
  @spec participant_name(Scope.t()) :: String.t()
  def participant_name(%Scope{user: %{id: id}}), do: "Reader " <> String.slice(id, -6, 6)
end
