  def t(message, bindings \\ %{})
  def t(nil, _bindings), do: nil
  def t(message, bindings) when is_binary(message), do: Gettext.gettext(LeitorWeb.Gettext, message, bindings)

  def html_locale, do: if(Gettext.get_locale(LeitorWeb.Gettext) == "pt_BR", do: "pt-BR", else: "en")

  def date(datetime) do
    Calendar.strftime(datetime, if(Gettext.get_locale(LeitorWeb.Gettext) == "pt_BR", do: "%d/%m/%Y", else: "%b %d"))
  end

  def client_dictionary, do: Map.new(Enum.filter(@dynamic_messages, &(&1 in @client_messages)), &{&1, t(&1)})

  def options(options) do
    Enum.map(options, fn
      {label, value} when is_binary(label) -> {t(label), value}
      option when is_binary(option) -> {t(option), option}
      option -> option
    end)
  end
