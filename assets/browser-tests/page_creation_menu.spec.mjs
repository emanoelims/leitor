import {test, expect} from '@playwright/test'
import {signIn} from './authentication.mjs'

test('the add-page menu offers a blank page and import from one primary button', async ({page},testInfo)=>{
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await signIn(page)
  const primary=page.locator('#new-free-page')
  const menu=page.locator('#page-create-trigger')
  const panel=page.locator('#page-create-panel')
  await expect(page.locator('#open-page-import')).toBeHidden()
  await menu.click()
  await primary.click()
  await expect(page).toHaveURL(/\/pages\/new$/)
  await expect(page.locator('#page-form')).toBeVisible()
  await page.goto('/pages')
  await menu.focus()
  await page.keyboard.press('ArrowDown')
  await expect(primary).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.locator('#open-page-import')).toBeFocused()
  await expect(menu).toHaveAttribute('aria-expanded','true')
  await expect(panel).toHaveCSS('opacity','1')
  await expect(menu).toHaveClass(/workspace-header-primary/)
  await expect(menu).toHaveCSS('height','36px')
  expect(await menu.locator('span').first().evaluate(el=>getComputedStyle(el).maskImage)).not.toBe('none')
  await page.screenshot({path:testInfo.outputPath('page-create-menu-desktop.png')})
  await page.keyboard.press('Escape')
  await expect(menu).toBeFocused()
  await expect(panel).toBeHidden()
  await menu.click()
  await page.locator('#open-page-import').click()
  await expect(page.locator('#page-import-dialog')).toBeVisible()
  await expect(panel).toBeHidden()
  await page.getByLabel('Text to import',{exact:true}).fill('# A connected action\n\nAn imported thought.')
  await page.keyboard.press('Escape')
  await expect(page.locator('#page-import-dialog')).toHaveCount(0)
  await expect(menu).toBeFocused()
  await menu.click()
  await page.locator('#open-page-import').click()
  await expect(page.getByLabel('Text to import',{exact:true})).toHaveValue('# A connected action\n\nAn imported thought.')
  await page.locator('#save-material').click()
  await expect(page.locator('#library-texts article h2')).toHaveText('A connected action')
  await page.evaluate(()=>localStorage.setItem('leitor:theme','ink'))
  await page.reload()
  await page.setViewportSize({width:390,height:844})
  await expect(primary).toBeHidden()
  await expect(menu).toBeInViewport()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await menu.click()
  await expect(page.locator('#open-page-import')).toBeInViewport()
  await expect(panel).toHaveCSS('opacity','1')
  await page.screenshot({path:testInfo.outputPath('page-create-menu-mobile-ink.png')})
  await primary.click()
  await expect(page).toHaveURL(/\/pages\/new$/)
  expect(errors).toEqual([])
})
