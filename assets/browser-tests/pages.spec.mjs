async function pastePage(page, text) {
  await page.getByRole('textbox', {name:'Your page text'}).evaluate((el, content) => {
    el.focus(); const data=new DataTransfer();data.setData('text/plain',content)
    el.dispatchEvent(new ClipboardEvent('paste',{bubbles:true,cancelable:true,clipboardData:data}))
  },text)
}
async function select(page, block, quote) {
  await page.locator(`#page-block-${block}`).evaluate((el, quote) => {
    const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);const nodes=[];let node
    while((node=walker.nextNode())) nodes.push(node)
    const text=nodes.map(n=>n.textContent).join(''),at=text.indexOf(quote)
    if(at<0) throw new Error(`Missing quote: ${quote}`)
    const point=offset=>{let size=0;for(const n of nodes){if(offset<=size+n.textContent.length)return {node:n,offset:offset-size};size+=n.textContent.length}}
    const first=point(at),last=point(at+quote.length),range=document.createRange()
    range.setStart(first.node,first.offset);range.setEnd(last.node,last.offset)
    const selected=window.getSelection();selected.removeAllRanges();selected.addRange(range)
    el.dispatchEvent(new MouseEvent('mouseup',{bubbles:true}))
  },quote)
  await expect(page.locator('#page-selection')).toBeVisible()
}

