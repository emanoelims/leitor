import {chooseOption} from './controls.mjs'
import {test, expect} from '@playwright/test'
import {signIn} from './authentication.mjs'

test('account languages and Claude models persist and translate the complete interface', async ({page}, testInfo) => {
  const errors=[]
  page.on('pageerror', error=>errors.push(error.message))
  await signIn(page)
  await page.locator('#account-menu-trigger').click()
  await page.locator('#account-preferences').click()
  await expect(page.locator('#preferences-form')).toBeVisible()
  await expect(page.locator('#preferences-reading-model option')).toHaveCount(2)
  await page.locator('#ai-key-value').fill('browser-test-own-anthropic-key')
  await page.locator('#ai-credential-form button[type=submit]').click()
  await expect(page.locator('#ai-key-value')).toHaveValue('')
  await expect(page.locator('#preferences-reading-model option')).toHaveCount(4)
  await chooseOption(page, page.locator('#preferences-locale'), 'pt_BR')
  await chooseOption(page, page.locator('#preferences-ai-locale'), 'en')
  await chooseOption(page, page.locator('#preferences-reading-model'), 'anthropic:claude-opus-5-5')
  await chooseOption(page, page.locator('#preferences-writing-model'), 'anthropic:claude-sonnet-5-5')
  await page.locator('#save-preferences').click()
  await expect(page.locator('html')).toHaveAttribute('lang','pt-BR')
  await expect(page.locator('#save-preferences')).toContainText('Salvar preferências')
  await expect(page.locator('#preferences-ai-locale')).toHaveValue('en')
  await page.reload()
  await expect(page.locator('#preferences-reading-model')).toHaveValue('anthropic:claude-opus-5-5')
  await expect(page.locator('#preferences-writing-model')).toHaveValue('anthropic:claude-sonnet-5-5')
  await page.screenshot({path:testInfo.outputPath('preferences-desktop.png'),fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.locator('#preferences-writing-model-trigger').scrollIntoViewIfNeeded()
  await expect(page.locator('#preferences-writing-model-trigger')).toBeInViewport()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('preferences-mobile.png'),fullPage:true})
  await page.setViewportSize({width:1440,height:960})
  await page.goto('/pages/new')
  const editor=page.getByRole('textbox',{name:'Texto da sua página'})
  await expect(editor).toBeVisible()
  await editor.fill('/título')
  await expect(page.locator('#writing-block-h1')).toBeVisible()
  await expect(page.locator('#writing-block-h1')).toContainText('Título 1')
  await editor.fill('/gerar')
  await expect(page.locator('#writing-block-ai')).toBeVisible()
  await page.keyboard.press('Escape')
  await editor.fill('Original English text.')
  await page.locator('#page-title').fill('Notebook')
  await page.locator('#page-save').click()
  await expect(page.locator('#page-reading')).toContainText('Original English text.')
  await page.locator('#reading-font').click()
  await expect(page.locator('#reading-appearance-panel')).toHaveAttribute('aria-label','Aparência da leitura')
  await page.goto('/pages')
  await expect(page.locator('#workspace-context-label')).toHaveText('Páginas')
  await expect(page.locator('#library-texts article h2')).toContainText('Notebook')
  await page.goto('/notebook?view=words')
  await expect(page.locator('#vocabulary-entries')).toContainText('Substantivos')
  await expect(page.locator('#vocabulary-entries')).toContainText('Pessoas, lugares, coisas')
  await page.goto('/settings')
  await chooseOption(page, page.locator('#preferences-locale'), 'en')
  await page.locator('#save-preferences').click()
  await expect(page.locator('html')).toHaveAttribute('lang','en')
  await expect(page.locator('#save-preferences')).toContainText('Save preferences')
  await expect(page.locator('#preferences-ai-locale')).toHaveValue('en')
  expect(errors).toEqual([])
})
